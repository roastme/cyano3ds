#!/usr/bin/env python3
"""/data persistence (2026-10-14): run the real /bin/dataflush on the host.

/data is a tmpfs; /bin/dataflush (generated by mkinitramfs.sh) saves it to
the card as two tars, only when something changed:
  android/data-cm7.tar       everything but app packages and dex caches
  android/data-cm7-apps.tar  /data/app + /data/app-private
This extracts the script from mkinitramfs.sh, points its paths at a temp
directory and runs it with the host's busybox (the same 1.36.1 the
initramfs uses), checking the change detection and the tmp+rename.
"""
import os
import subprocess
import tarfile
import tempfile
import time
from t3ds import *

if not have("busybox"):
    skip("no host busybox")

init = read(SCRIPTS / "mkinitramfs.sh")
script = heredoc(init, "dataflush").replace("@@DATATAR@@", "data-cm7.tar")

check("'*'|app|app-private|dalvik-cache|lost+found) ;;" in script,
      "the state tar must skip apps, dex caches and lost+found")
check("$BB flock -n 9 || exit 0" in script, "periodic saves must not queue behind each other")
check("flock -w" not in script, "busybox flock has no -w (the lid/shutdown saves exited with its usage text)")
check("mv -f \"$name.tmp\" \"$name\"" in script, "tar is not written tmp+rename")
check("sleep 60" in init and "/bin/dataflush periodic" in init, "periodic saver is not every 60 s")
check("/bin/dataflush shutdown" in init, "clean shutdown does not save /data")
check('APPS_TAR="${DATA_TAR%.tar}-apps.tar"' in init, "boot does not restore the apps tar")

with tempfile.TemporaryDirectory() as td:
    td = pathlib.Path(td)
    data, out, runp = td / "data", td / "sd/android", td / "probe"
    for d in (data / "system", data / "data/com.example/shared_prefs", data / "app",
              data / "dalvik-cache", out, runp):
        d.mkdir(parents=True, exist_ok=True)
    (data / "system/packages.xml").write_text("<packages/>")
    (data / "data/com.example/shared_prefs/p.xml").write_text("<map/>")
    (data / "app/game.apk").write_bytes(b"PK" + b"\0" * 4000)
    (data / "dalvik-cache/x.dex").write_bytes(b"dex")
    # Ubuntu's busybox has no flock applet (the initramfs one does)
    bb = td / "bb"
    # and the real one only takes -s/-x/-u/-n: refuse anything else, like it
    bb.write_text('#!/bin/sh\na=$1; shift\n'
                  'if [ "$a" = flock ]; then\n'
                  '\tcase "$1" in -s|-x|-u|-n|[0-9]*) ;; *) echo "flock: bad option $1" >&2; exit 1 ;; esac\n'
                  '\tbusybox flock --help >/dev/null 2>&1 || exec flock "$@"\nfi\n'
                  'exec busybox "$a" "$@"\n')
    bb.chmod(0o755)
    s = (script.replace("BB=/bin/busybox", f"BB={bb}")
               .replace("OUT=/mnt/sd/android", f"OUT={out}")
               .replace("RUN=/mnt/probe", f"RUN={runp}")
               .replace("cd /data ", f"cd {data} "))
    flush = td / "dataflush"
    flush.write_text(s)
    flush.chmod(0o755)

    def go(why="periodic"):
        r = run(["busybox", "sh", str(flush), why])
        check(r.returncode == 0, f"dataflush {why} failed: {r.stdout}{r.stderr}")
        return r.stdout

    o1 = go()
    state, apps = out / "data-cm7.tar", out / "data-cm7-apps.tar"
    check(state.exists() and apps.exists(), "first save wrote no tars: " + o1)
    if state.exists():
        names = tarfile.open(state).getnames()
        check("system/packages.xml" in names, "state tar lacks system/packages.xml")
        check("data/com.example/shared_prefs/p.xml" in names, "state tar lacks app data")
        check(not any(n.startswith(("app", "dalvik-cache")) for n in names),
              "state tar contains apps or dex caches")
    if apps.exists():
        check("app/game.apk" in tarfile.open(apps).getnames(), "apps tar lacks /data/app")

    m1 = (state.stat().st_mtime_ns, apps.stat().st_mtime_ns)
    time.sleep(1.1)
    o2 = go()
    check(o2.strip() == "", "nothing changed but a tar was rewritten: " + o2)
    check(m1 == (state.stat().st_mtime_ns, apps.stat().st_mtime_ns),
          "unchanged data rewrote the card")

    time.sleep(1.1)
    (data / "data/com.example/shared_prefs/p.xml").write_text("<map><int name='x'/></map>")
    o3 = go("lid-close")
    check("saved data-cm7.tar" in o3 and "apps" not in o3,
          "a settings change must rewrite only the state tar: " + o3)

    # a lid-close save waits for a save in progress instead of failing
    time.sleep(1.1)
    (data / "system/packages.xml").write_text("<packages v='2'/>")
    holder = subprocess.Popen(["flock", str(runp / "dataflush.lock"), "sleep", "2"])
    time.sleep(0.3)
    o5 = go("lid-close")
    holder.wait()
    check("saved data-cm7.tar" in o5, "lid-close save did not wait for the lock: " + o5)

    time.sleep(1.1)
    (data / "app/game.apk").unlink()
    o4 = go()
    check("saved data-cm7-apps.tar" in o4, "uninstalling an app did not rewrite the apps tar: " + o4)
    check(not list(out.glob("*.tmp")), "a .tmp archive was left behind")
done()
